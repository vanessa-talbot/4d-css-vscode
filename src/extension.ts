import * as fs from 'fs';
import * as path from 'path';
import * as vscode from 'vscode';
import * as jsonc from 'jsonc-parser';

import { Rule, parseStylesheet, splitSelectorList, stripComments } from './parser';
import {
  CSS_ALIASES,
  FORBIDDEN_ATTRIBUTES,
  FormIndex,
  MEDIA_FEATURES,
  ObjectIndex,
  PropertyInfo,
  buildFormIndex,
  buildIndex
} from './schema';
import { allowedProperties, analyzeSelector, validateStylesheet } from './validator';
import { formCompletions, validateForm } from './formValidator';
import { createRefResolver, formFileCandidates } from './jsonRef';
import { formClasses } from './cssClasses';
import { DocumentationViewProvider } from './docsView';

const LANGUAGE = '4d-css';
const FORM_EXTENSION = /\.4dform$/i;
const CSS_FILE = /(\.4dcss|[\\/]styleSheets(_mac|_windows)?\.css)$/i;

/** Files picked up by the "Validate Workspace" command. */
const WORKSPACE_GLOBS = ['**/*.4DForm', '**/*.4dcss', '**/styleSheets*.css'];
/** Files a picture attribute of a form ("icon", "picture", ...) can point at. */
const PICTURE_FILES = '**/*.{png,jpg,jpeg,gif,svg,bmp,tif,tiff,ico,pdf,heic,webp}';
const WORKSPACE_EXCLUDE = '**/{node_modules,.git,Logs,Data}/**';
const EXCLUDED_FOLDER = /[\\/](node_modules|\.git|Logs|Data)[\\/]/;

let index: ObjectIndex = new Map();
let formIndex: FormIndex = { index: new Map(), typeToDefinition: new Map() };
let diagnostics: vscode.DiagnosticCollection;
let formDiagnostics: vscode.DiagnosticCollection;
let documentationView: DocumentationViewProvider;
/** Documents validated by the workspace scan: their diagnostics survive closing the document. */
const scanned = new Set<string>();

function isFormDocument(document: vscode.TextDocument): boolean {
  return FORM_EXTENSION.test(document.fileName);
}

function isCssDocument(document: vscode.TextDocument): boolean {
  return document.languageId === LANGUAGE || CSS_FILE.test(document.fileName);
}

export function activate(context: vscode.ExtensionContext) {
  diagnostics = vscode.languages.createDiagnosticCollection(LANGUAGE);
  formDiagnostics = vscode.languages.createDiagnosticCollection('4d-form');
  documentationView = new DocumentationViewProvider(index, insertPropertyAtCursor, insertMediaFeatureAtCursor);
  context.subscriptions.push(
    diagnostics,
    formDiagnostics,
    vscode.commands.registerCommand('4dCss.reloadSchema', reload),
    vscode.commands.registerCommand('4dCss.validateWorkspace', validateWorkspace),
    vscode.commands.registerCommand('4dCss.showDocumentation', showDocumentation),
    vscode.window.registerWebviewViewProvider(DocumentationViewProvider.viewType, documentationView)
  );

  function reload(): void {
    try {
      const schema = JSON.parse(fs.readFileSync(schemaPath(context), 'utf8'));
      index = buildIndex(schema);
      formIndex = buildFormIndex(schema);
      documentationView.updateIndex(index);
      updateDocumentationObjectType(vscode.window.activeTextEditor);
      for (const document of vscode.workspace.textDocuments) {
        validate(document);
        validateFormDocument(document);
      }
    } catch (error) {
      vscode.window.showErrorMessage(`4D CSS: unable to load schema: ${String(error)}`);
    }
  }
  reload();

  /** Forms depend on the classes of the style sheets: revalidate the open ones when a sheet changes. */
  const revalidateForms = () => {
    for (const document of vscode.workspace.textDocuments) validateFormDocument(document);
  };

  const validateAny = (document: vscode.TextDocument) => {
    validate(document);
    validateFormDocument(document);
    if (/\.css$/i.test(document.fileName)) revalidateForms();
    if (vscode.window.activeTextEditor?.document === document) updateDocumentationObjectType(vscode.window.activeTextEditor);
  };

  /**
   * Files written on disk without an editor (generated by a script or an AI agent) are validated
   * too, so that their problems show up without opening them. Only the file that changed is read.
   */
  const validateOnDisk = async (uri: vscode.Uri) => {
    if (!vscode.workspace.getConfiguration('4dCss').get<boolean>('validateOnDiskChange', true)) return;
    if (EXCLUDED_FOLDER.test(uri.fsPath) || !(FORM_EXTENSION.test(uri.fsPath) || CSS_FILE.test(uri.fsPath))) return;
    let document: vscode.TextDocument;
    try {
      document = await vscode.workspace.openTextDocument(uri);
    } catch {
      return;
    }
    // Keeps the diagnostics when VS Code disposes of the document, as for "Validate Workspace".
    scanned.add(uri.toString());
    validateAny(document);
  };
  const forgetOnDisk = (uri: vscode.Uri) => {
    if (!scanned.delete(uri.toString())) return;
    diagnostics.delete(uri);
    formDiagnostics.delete(uri);
  };

  const sourceWatcher = vscode.workspace.createFileSystemWatcher('**/*.{4DForm,4dcss}');
  const styleSheetWatcher = vscode.workspace.createFileSystemWatcher('**/*.css');
  // Picture paths only depend on the existence of the file, not on its contents.
  const pictureWatcher = vscode.workspace.createFileSystemWatcher(PICTURE_FILES, false, true, false);
  context.subscriptions.push(
    sourceWatcher,
    sourceWatcher.onDidCreate(validateOnDisk),
    sourceWatcher.onDidChange(validateOnDisk),
    sourceWatcher.onDidDelete(forgetOnDisk),
    styleSheetWatcher.onDidCreate(validateOnDisk),
    styleSheetWatcher.onDidChange(validateOnDisk),
    styleSheetWatcher.onDidDelete(forgetOnDisk),
    styleSheetWatcher,
    pictureWatcher,
    pictureWatcher.onDidCreate(revalidateForms),
    pictureWatcher.onDidDelete(revalidateForms),
    styleSheetWatcher.onDidCreate(revalidateForms),
    styleSheetWatcher.onDidChange(revalidateForms),
    styleSheetWatcher.onDidDelete(revalidateForms),
    vscode.workspace.onDidChangeTextDocument(event => validateAny(event.document)),
    vscode.window.onDidChangeActiveTextEditor(updateDocumentationObjectType),
    vscode.window.onDidChangeTextEditorSelection(event => updateDocumentationObjectType(event.textEditor)),
    vscode.workspace.onDidOpenTextDocument(validateAny),
    vscode.workspace.onDidCloseTextDocument(document => {
      if (scanned.has(document.uri.toString())) return;
      diagnostics.delete(document.uri);
      formDiagnostics.delete(document.uri);
    }),
    vscode.workspace.onDidChangeConfiguration(event => {
      if (event.affectsConfiguration('4dCss.schemaPath')) reload();
    }),
    vscode.languages.registerCompletionItemProvider(LANGUAGE, completionProvider, '.', '#', '[', ':', ' ', '('),
    vscode.languages.registerHoverProvider(LANGUAGE, hoverProvider),
    vscode.languages.registerCompletionItemProvider('json', formCompletionProvider, ' ', '"', ':'),
    vscode.languages.registerCodeActionsProvider('json', formCodeActionProvider, {
      providedCodeActionKinds: [vscode.CodeActionKind.QuickFix]
    }),
    vscode.languages.registerCodeActionsProvider([LANGUAGE, 'css'], styleSheetCodeActionProvider, {
      providedCodeActionKinds: [vscode.CodeActionKind.QuickFix]
    })
  );
}

async function showDocumentation(): Promise<void> {
  await vscode.commands.executeCommand('workbench.view.extension.4dCss');
  await vscode.commands.executeCommand(`${DocumentationViewProvider.viewType}.focus`);
}

async function insertPropertyAtCursor(name: string): Promise<void> {
  const editor = vscode.window.activeTextEditor;
  if (!editor || !isCssDocument(editor.document)) {
    vscode.window.showWarningMessage('4D CSS: open a 4D style sheet to insert a property.');
    return;
  }

  await editor.insertSnippet(new vscode.SnippetString(`${name}: $0;`));
}

async function insertMediaFeatureAtCursor(name: string, value: string): Promise<void> {
  const editor = vscode.window.activeTextEditor;
  if (!editor || !isCssDocument(editor.document)) {
    vscode.window.showWarningMessage('4D CSS: open a 4D style sheet to insert a media rule.');
    return;
  }

  await editor.insertSnippet(new vscode.SnippetString(`@media (${name}: ${value}) {\n\t$0\n}`));
}

function updateDocumentationObjectType(editor: vscode.TextEditor | undefined): void {
  documentationView.updateActiveObjectType(editor ? objectTypeAtCursor(editor) : undefined);
}

function objectTypeAtCursor(editor: vscode.TextEditor): string | undefined {
  if (!isCssDocument(editor.document)) return undefined;

  const offset = editor.document.offsetAt(editor.selection.active);
  const rule = ruleAround(editor.document, offset);
  if (!rule) return undefined;

  for (const group of splitSelectorList(rule.selector, rule.selectorOffset)) {
    const groupEnd = group.offset + group.text.length;
    if (offset >= group.offset && offset <= groupEnd) {
      return analyzeSelector(group.text, group.offset, index).types[0];
    }
  }

  return analyzeSelector(rule.selector, rule.selectorOffset, index).types[0];
}

function ruleAround(document: vscode.TextDocument, offset: number): Rule | undefined {
  return parseStylesheet(document.getText()).rules.find(
    rule => offset >= rule.selectorOffset && offset <= rule.bodyEnd
  );
}

function validateFormDocument(document: vscode.TextDocument): void {
  if (!isFormDocument(document)) return;
  const text = document.getText();
  let issues: ReturnType<typeof validateForm> = [];
  try {
    const form = jsonc.parse(text);
    const resolver = createRefResolver(document.uri.fsPath, form);
    const pictureExists = (picture: string) => formFileCandidates(document.uri.fsPath, picture).some(fs.existsSync);
    issues = validateForm(text, formIndex, resolver, formClasses(document.uri.fsPath, form, readStyleSheet), pictureExists);
  } catch {
    return;
  }
  formDiagnostics.set(
    document.uri,
    issues.map(item => {
      const range = new vscode.Range(
        document.positionAt(item.offset),
        document.positionAt(item.offset + item.length)
      );
      const diagnostic = new vscode.Diagnostic(range, item.message, SEVERITIES[item.severity]);
      diagnostic.source = '4D Form';
      if (item.code) diagnostic.code = item.code;
      if (item.related) {
        const start = new vscode.Position(item.related.line, item.related.character);
        diagnostic.relatedInformation = [
          new vscode.DiagnosticRelatedInformation(
            new vscode.Location(vscode.Uri.file(item.related.file), new vscode.Range(start, start.translate(0, item.related.length))),
            item.related.message
          )
        ];
      }
      return diagnostic;
    })
  );
}

const SEVERITIES = {
  error: vscode.DiagnosticSeverity.Error,
  warning: vscode.DiagnosticSeverity.Warning,
  info: vscode.DiagnosticSeverity.Information
};

/** Form diagnostics fixed by removing the attribute from the form (the style sheet or sibling value then applies). */
const REMOVABLE_ATTRIBUTE_CODES = new Set([
  'cssOverride',
  'cssDuplicate',
  'inheritanceBlocked',
  'inheritedDuplicate',
  'fontThemeIgnored'
]);

/** Removals that leave the rendering unchanged, offered all at once for a file. */
const SAFE_REMOVAL_CODES = new Set(['cssDuplicate', 'inheritedDuplicate', 'fontThemeIgnored']);

/** Duplicates of a style sheet value: the attribute repeats what the cascade would give anyway. */
const DUPLICATE_CODES = new Set(['cssDuplicate', 'inheritedDuplicate']);

const formCodeActionProvider: vscode.CodeActionProvider = {
  provideCodeActions(document, _range, context) {
    if (!isFormDocument(document)) return undefined;
    const text = document.getText();
    const actions: vscode.CodeAction[] = [];
    for (const diagnostic of context.diagnostics) {
      if (diagnosticCode(diagnostic) === 'geometryOverride') {
        const action = addImportantInStyleSheet(diagnostic);
        if (action) actions.push(action);
        continue;
      }
      if (!REMOVABLE_ATTRIBUTE_CODES.has(diagnosticCode(diagnostic))) continue;
      const attribute = attributePath(document, text, diagnostic);
      if (!attribute) continue;
      const action = new vscode.CodeAction(
        `Remove "${attribute[attribute.length - 1]}" from the form`,
        vscode.CodeActionKind.QuickFix
      );
      action.diagnostics = [diagnostic];
      action.edit = new vscode.WorkspaceEdit();
      for (const change of jsonc.modify(text, attribute, undefined, {})) {
        action.edit.replace(
          document.uri,
          new vscode.Range(document.positionAt(change.offset), document.positionAt(change.offset + change.length)),
          change.content
        );
      }
      action.isPreferred = SAFE_REMOVAL_CODES.has(diagnosticCode(diagnostic));
      actions.push(action);
    }

    if (context.diagnostics.some(diagnostic => DUPLICATE_CODES.has(diagnosticCode(diagnostic)))) {
      const duplicates = (formDiagnostics.get(document.uri) ?? []).filter(diagnostic =>
        DUPLICATE_CODES.has(diagnosticCode(diagnostic))
      );
      const attributes = duplicates
        .map(diagnostic => attributePath(document, text, diagnostic))
        .filter((attribute): attribute is jsonc.JSONPath => attribute !== undefined);
      if (attributes.length > 1) {
        const action = new vscode.CodeAction(
          `Remove the ${attributes.length} attributes repeating a style sheet value in this form`,
          vscode.CodeActionKind.QuickFix
        );
        action.diagnostics = duplicates;
        action.edit = new vscode.WorkspaceEdit();
        action.edit.replace(document.uri, fullRange(document), removeAttributes(text, attributes));
        actions.push(action);
      }
    }
    return actions;
  }
};

/**
 * Quick fix of a form coordinate hiding a style sheet value: the 4D form editor writes the
 * coordinate again on each save, so the declaration of the style sheet is made !important instead.
 */
function addImportantInStyleSheet(diagnostic: vscode.Diagnostic): vscode.CodeAction | undefined {
  const declaration = diagnostic.relatedInformation?.[0]?.location;
  if (!declaration) return undefined;
  const action = new vscode.CodeAction(
    `Declare it !important in ${path.basename(declaration.uri.fsPath)}`,
    vscode.CodeActionKind.QuickFix
  );
  action.diagnostics = [diagnostic];
  action.edit = new vscode.WorkspaceEdit();
  action.edit.insert(declaration.uri, declaration.range.end, ' !important');
  action.isPreferred = true;
  return action;
}

/** Adds !important to the coordinates declared in a style sheet, which the form attributes would beat otherwise. */
const styleSheetCodeActionProvider: vscode.CodeActionProvider = {
  provideCodeActions(document, _range, context) {
    const isGeometry = (diagnostic: vscode.Diagnostic) =>
      diagnostic.source === '4D CSS' && diagnostic.code === 'geometryNotImportant';
    const actions: vscode.CodeAction[] = [];
    for (const diagnostic of context.diagnostics.filter(isGeometry)) {
      const action = new vscode.CodeAction('Add !important', vscode.CodeActionKind.QuickFix);
      action.diagnostics = [diagnostic];
      action.edit = new vscode.WorkspaceEdit();
      action.edit.insert(document.uri, diagnostic.range.end, ' !important');
      action.isPreferred = true;
      actions.push(action);
    }
    const all = (diagnostics.get(document.uri) ?? []).filter(isGeometry);
    if (actions.length && all.length > 1) {
      const action = new vscode.CodeAction(
        `Add !important to the ${all.length} left/top/width/height declarations of this file`,
        vscode.CodeActionKind.QuickFix
      );
      action.diagnostics = [...all];
      action.edit = new vscode.WorkspaceEdit();
      for (const diagnostic of all) action.edit.insert(document.uri, diagnostic.range.end, ' !important');
      actions.push(action);
    }
    return actions;
  }
};

function diagnosticCode(diagnostic: vscode.Diagnostic): string {
  return diagnostic.source === '4D Form' ? String(diagnostic.code) : '';
}

/** JSON path of the attribute whose key the diagnostic underlines. */
function attributePath(document: vscode.TextDocument, text: string, diagnostic: vscode.Diagnostic): jsonc.JSONPath | undefined {
  const location = jsonc.getLocation(text, document.offsetAt(diagnostic.range.start));
  return location.isAtPropertyKey ? location.path : undefined;
}

/** Removes the attributes one after the other, so that the commas of neighbouring ones stay valid. */
function removeAttributes(text: string, attributes: jsonc.JSONPath[]): string {
  return attributes.reduce((current, attribute) => jsonc.applyEdits(current, jsonc.modify(current, attribute, undefined, {})), text);
}

function fullRange(document: vscode.TextDocument): vscode.Range {
  return new vscode.Range(document.positionAt(0), document.positionAt(document.getText().length));
}

/** Contents of a style sheet, taken from its editor when open so that unsaved edits count. */
function readStyleSheet(file: string): string | undefined {
  const open = vscode.workspace.textDocuments.find(document => document.uri.fsPath === file);
  if (open) return open.getText();
  try {
    return fs.readFileSync(file, 'utf8');
  } catch {
    return undefined;
  }
}

const formCompletionProvider: vscode.CompletionItemProvider = {
  provideCompletionItems(document, position) {
    if (!isFormDocument(document)) return undefined;
    const offset = document.offsetAt(position);
    let result: ReturnType<typeof formCompletions>;
    try {
      result = formCompletions(document.getText(), offset, formIndex);
    } catch {
      return undefined;
    }

    if (result.keys) {
      return result.keys.map(([name, info]) => {
        const item = new vscode.CompletionItem(name, vscode.CompletionItemKind.Property);
        item.detail = '4D form attribute';
        item.documentation = documentation(info);
        item.insertText = new vscode.SnippetString(`"${name}": $0`);
        return item;
      });
    }
    if (result.values) {
      return result.values.info.enums.map(value => {
        const item = new vscode.CompletionItem(`"${value}"`, vscode.CompletionItemKind.Value);
        item.insertText = `"${value}"`;
        item.detail = `Value for ${result.values!.property}`;
        return item;
      });
    }
    return undefined;
  }
};

export function deactivate() {
  diagnostics?.dispose();
  formDiagnostics?.dispose();
}

/** Validates every `.4DForm` and 4D style sheet of the workspace, including closed files. */
async function validateWorkspace(): Promise<void> {
  if (!vscode.workspace.workspaceFolders?.length) {
    vscode.window.showWarningMessage('4D CSS: no folder is open.');
    return;
  }

  const found = new Map<string, vscode.Uri>();
  for (const glob of WORKSPACE_GLOBS) {
    for (const uri of await vscode.workspace.findFiles(glob, WORKSPACE_EXCLUDE)) {
      found.set(uri.toString(), uri);
    }
  }
  if (!found.size) {
    vscode.window.showInformationMessage('4D CSS: no .4DForm or 4D style sheet found in the workspace.');
    return;
  }

  scanned.clear();
  diagnostics.clear();
  formDiagnostics.clear();

  const problems = await vscode.window.withProgress(
    { location: vscode.ProgressLocation.Notification, title: '4D CSS: validating workspace…' },
    async progress => {
      let count = 0;
      let done = 0;
      for (const uri of found.values()) {
        progress.report({ message: `${++done}/${found.size}`, increment: 100 / found.size });
        let document: vscode.TextDocument;
        try {
          document = await vscode.workspace.openTextDocument(uri);
        } catch {
          continue;
        }
        scanned.add(uri.toString());
        validate(document);
        validateFormDocument(document);
        count += (diagnostics.get(uri)?.length ?? 0) + (formDiagnostics.get(uri)?.length ?? 0);
      }
      return count;
    }
  );

  vscode.window.showInformationMessage(
    `4D CSS: ${found.size} file(s) validated, ${problems} problem(s) found.`
  );
  if (problems) vscode.commands.executeCommand('workbench.action.problems.focus');
}

function schemaPath(context: vscode.ExtensionContext): string {
  const configured = vscode.workspace.getConfiguration('4dCss').get<string>('schemaPath', '');
  if (configured) {
    if (path.isAbsolute(configured)) return configured;
    const root = vscode.workspace.workspaceFolders?.[0]?.uri.fsPath;
    if (root) return path.join(root, configured);
  }
  return path.join(context.extensionPath, 'schema', 'formsSchema.json');
}

function validate(document: vscode.TextDocument): void {
  if (!isCssDocument(document)) return;
  const sheet = parseStylesheet(document.getText());
  diagnostics.set(
    document.uri,
    validateStylesheet(sheet, index).map(item => {
      const range = new vscode.Range(
        document.positionAt(item.offset),
        document.positionAt(item.offset + item.length)
      );
      const diagnostic = new vscode.Diagnostic(
        range,
        item.message,
        item.severity === 'error' ? vscode.DiagnosticSeverity.Error : vscode.DiagnosticSeverity.Warning
      );
      diagnostic.source = '4D CSS';
      if (item.code) diagnostic.code = item.code;
      return diagnostic;
    })
  );
}

/** Rule whose declaration block contains `offset`, if any. */
function ruleAt(document: vscode.TextDocument, offset: number): Rule | undefined {
  return parseStylesheet(document.getText()).rules.find(
    rule => offset >= rule.bodyStart && offset <= rule.bodyEnd
  );
}

const completionProvider: vscode.CompletionItemProvider = {
  provideCompletionItems(document, position) {
    const offset = document.offsetAt(position);
    const text = stripComments(document.getText()).slice(0, offset);
    const line = text.slice(text.lastIndexOf('\n') + 1);

    const mediaValue = line.match(/@media[^{]*\(\s*([A-Za-z-]+)\s*:\s*[\w-]*$/);
    if (mediaValue) {
      return (MEDIA_FEATURES.get(mediaValue[1]) ?? []).map(value => valueItem(value, mediaValue[1]));
    }
    if (/@media[^{]*\($/.test(line)) {
      return [...MEDIA_FEATURES.keys()].map(feature => valueItem(feature, 'media feature'));
    }

    const rule = ruleAt(document, offset);
    if (!rule) return selectorCompletions(line);

    const property = line.match(/([A-Za-z_][\w-]*)\s*:[^;{}]*$/);
    if (property) return valueCompletions(rule, property[1]);

    return propertyCompletions(rule);
  }
};

function selectorCompletions(line: string): vscode.CompletionItem[] {
  if (/\[\s*[\w-]*$/.test(line)) {
    const attributes = new Map<string, PropertyInfo>();
    for (const properties of index.values()) for (const [name, info] of properties) attributes.set(name, info);
    return [...attributes.values()].map(info => propertyItem(info, info.name, 'attribute selector'));
  }
  return [...index.keys()].map(type => {
    const item = new vscode.CompletionItem(type, vscode.CompletionItemKind.Class);
    item.detail = '4D object type';
    return item;
  });
}

function propertyCompletions(rule: Rule): vscode.CompletionItem[] {
  const types = analyzeSelector(rule.selector, rule.selectorOffset, index).types;
  const properties = allowedProperties(index, types);
  const scope = types.length ? types.join(', ') : 'all objects';

  const items = [...properties.values()].map(info => {
    const item = propertyItem(info, info.name, scope);
    item.insertText = new vscode.SnippetString(`${info.name}: $0;`);
    return item;
  });

  for (const [cssName, jsonName] of CSS_ALIASES) {
    const info = properties.get(jsonName);
    if (!info) continue;
    const item = propertyItem(info, cssName, `CSS alias of ${jsonName}`);
    item.insertText = new vscode.SnippetString(`${cssName}: $0;`);
    item.sortText = `z${cssName}`;
    items.push(item);
  }
  return items;
}

function valueCompletions(rule: Rule, property: string): vscode.CompletionItem[] {
  const name = CSS_ALIASES.get(property) ?? property;
  if (FORBIDDEN_ATTRIBUTES.has(name)) return [];
  const types = analyzeSelector(rule.selector, rule.selectorOffset, index).types;
  const info = allowedProperties(index, types).get(name);
  if (!info) return [];

  const items = info.enums.map(value => valueItem(value, name));
  if (!info.enums.length && info.types.includes('boolean')) {
    items.push(valueItem('true', name), valueItem('false', name));
  }
  if (info.refs.includes('picture')) {
    const item = new vscode.CompletionItem('url()', vscode.CompletionItemKind.Snippet);
    item.insertText = new vscode.SnippetString('url("$1")');
    item.detail = `Picture path for ${name}`;
    items.push(item);
  }
  return items;
}

function propertyItem(info: PropertyInfo, label: string, scope: string): vscode.CompletionItem {
  const item = new vscode.CompletionItem(label, vscode.CompletionItemKind.Property);
  item.detail = `4D CSS · ${scope}`;
  item.documentation = documentation(info);
  return item;
}

function valueItem(label: string, owner: string): vscode.CompletionItem {
  const item = new vscode.CompletionItem(label, vscode.CompletionItemKind.Value);
  item.detail = `Value for ${owner}`;
  return item;
}

function documentation(info: PropertyInfo): vscode.MarkdownString {
  const lines: string[] = [];
  if (info.comment) lines.push(info.comment);
  if (info.enums.length) lines.push(`**Values**: ${info.enums.join(' · ')}`);
  else if (info.refs.length) lines.push(`**Type**: ${info.refs.join(', ')}`);
  else if (info.types.length) lines.push(`**Type**: ${info.types.join(', ')}`);
  return new vscode.MarkdownString(lines.join('\n\n'));
}

const hoverProvider: vscode.HoverProvider = {
  provideHover(document, position) {
    const wordRange = document.getWordRangeAtPosition(position, /[A-Za-z_][\w-]*/);
    if (!wordRange) return undefined;
    const word = document.getText(wordRange);
    const offset = document.offsetAt(wordRange.start);
    const rule = ruleAt(document, offset);

    if (!rule && index.has(word)) {
      return new vscode.Hover(
        new vscode.MarkdownString(`**${word}** — 4D object type (${index.get(word)!.size} styleable attributes)`),
        wordRange
      );
    }
    if (!rule) return undefined;

    const name = CSS_ALIASES.get(word) ?? word;
    const types = analyzeSelector(rule.selector, rule.selectorOffset, index).types;
    const info = allowedProperties(index, types).get(name);
    if (!info) return undefined;

    const markdown = new vscode.MarkdownString(`**${name}**\n\n`);
    markdown.appendMarkdown(documentation(info).value);
    return new vscode.Hover(markdown, wordRange);
  }
};
